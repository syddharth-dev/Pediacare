CREATE TABLE children (
    id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    record_no VARCHAR(13) NOT NULL UNIQUE,
    first_name VARCHAR(255) NOT NULL,
    middle_name VARCHAR(255) NULL,
    last_name VARCHAR(255) NOT NULL,
    suffix VARCHAR(32) NULL,
    sex ENUM('M', 'F') NOT NULL,
    date_of_birth DATE NOT NULL,
    place_of_birth VARCHAR(255) NOT NULL,
    purok_id INT UNSIGNED NOT NULL,
    address TEXT NOT NULL,
    mother_name VARCHAR(255) NOT NULL,
    father_name VARCHAR(255) NULL,
    guardian_name VARCHAR(255) NOT NULL,
    guardian_relation VARCHAR(100) NOT NULL,
    contact_no VARCHAR(32) NOT NULL,
    philhealth_no VARCHAR(32) NULL,
    birth_weight_kg DECIMAL(4,2) NULL,
    birth_length_cm DECIMAL(4,1) NULL,
    notes TEXT NULL,
    archived_at DATETIME NULL,
    archive_reason TEXT NULL,
    created_by INT UNSIGNED NOT NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    CONSTRAINT children_purok_fk FOREIGN KEY (purok_id) REFERENCES puroks(id) ON DELETE RESTRICT,
    CONSTRAINT children_creator_fk FOREIGN KEY (created_by) REFERENCES users(id) ON DELETE RESTRICT,
    INDEX children_name (last_name, first_name),
    INDEX children_birth_date (date_of_birth),
    INDEX children_purok (purok_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
