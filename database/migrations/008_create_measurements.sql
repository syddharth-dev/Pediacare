CREATE TABLE measurements (
    id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    child_id INT UNSIGNED NOT NULL,
    measured_at DATE NOT NULL,
    weight_kg DECIMAL(5,2) NOT NULL,
    height_cm DECIMAL(5,1) NOT NULL,
    position ENUM('LYING', 'STANDING') NOT NULL,
    muac_cm DECIMAL(4,1) NULL,
    age_months INT UNSIGNED NOT NULL,
    bmi DECIMAL(5,2) NOT NULL,
    wfa_z DECIMAL(5,2) NULL,
    hfa_z DECIMAL(5,2) NULL,
    wfh_z DECIMAL(5,2) NULL,
    bmi_z DECIMAL(5,2) NULL,
    wfa_status VARCHAR(32) NULL,
    hfa_status VARCHAR(32) NULL,
    wfh_status VARCHAR(32) NULL,
    bmi_status VARCHAR(32) NULL,
    implausible_confirmed TINYINT NOT NULL DEFAULT 0,
    measured_by INT UNSIGNED NOT NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT measurements_child_fk FOREIGN KEY (child_id) REFERENCES children(id) ON DELETE RESTRICT,
    CONSTRAINT measurements_actor_fk FOREIGN KEY (measured_by) REFERENCES users(id) ON DELETE RESTRICT,
    CONSTRAINT measurements_positive_weight CHECK (weight_kg > 0),
    CONSTRAINT measurements_positive_height CHECK (height_cm > 0),
    CONSTRAINT measurements_positive_muac CHECK (muac_cm IS NULL OR muac_cm > 0),
    CONSTRAINT measurements_positive_bmi CHECK (bmi > 0),
    CONSTRAINT measurements_confirmation CHECK (implausible_confirmed IN (0, 1)),
    INDEX measurements_child_date (child_id, measured_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
